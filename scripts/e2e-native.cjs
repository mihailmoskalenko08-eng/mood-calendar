// Шифрование в сборке для iPhone: NATIVE=1 npx vite build --outDir dist-native && npx vite preview --outDir dist-native --base / --port 4180 & node scripts/e2e-native.cjs
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
;(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 402, height: 874 } })
  const p = await ctx.newPage()
  const errs = []; p.on('pageerror', e => errs.push(String(e)))
  await p.goto('' + (process.env.BASE || 'http://localhost:4180/') + ''); await p.waitForTimeout(1000)
  await p.click('.onboard .cta'); await p.click('text=Начать'); await p.waitForTimeout(300)
  await p.click('.scale-row:has-text("Хорошо")')
  await p.fill('.note textarea', 'секретная заметка'); await p.locator('.note textarea').blur(); await p.waitForTimeout(600)
  await p.click('.tabbar-btn:has-text("Ещё")')
  await p.click('text=Задать код')
  for (const k of '2580') await p.click(`.pin-setup .key[aria-label="${k}"]`)
  for (const k of '2580') await p.click(`.pin-setup .key[aria-label="${k}"]`)
  await p.waitForSelector('text=отметки зашифрованы', { timeout: 15000 })
  await p.waitForTimeout(800)
  const dump = await p.evaluate(() => JSON.stringify(Object.fromEntries(Object.keys(localStorage).map(k => [k, localStorage.getItem(k)]))))
  assert.ok(!dump.includes('секретная'), 'открытый текст не должен лежать в хранилище')
  assert.ok(dump.includes('ottenki:data:enc'), 'зашифрованные данные есть')
  // правка после включения шифрования
  await p.click('.tabbar-btn:has-text("День")')
  await p.fill('.note textarea', 'секретная заметка 2'); await p.locator('.note textarea').blur(); await p.waitForTimeout(800)
  await p.reload(); await p.waitForTimeout(1200)
  assert.equal(await p.locator('.lock').count(), 1, 'при запуске — экран кода')
  assert.equal(await p.locator('.app').count(), 0)
  for (const k of '1111') await p.click(`.lock .key[aria-label="${k}"]`)
  await p.waitForSelector('text=Неверный код')
  await p.waitForTimeout(700)
  for (const k of '2580') await p.click(`.lock .key[aria-label="${k}"]`)
  await p.waitForSelector('.app', { timeout: 15000 })
  assert.equal(await p.inputValue('.note textarea'), 'секретная заметка 2')
  // снять код — данные снова открыто
  await p.click('.tabbar-btn:has-text("Ещё")')
  await p.click('text=Снять код')
  for (const k of '2580') await p.click(`.pin-setup .key[aria-label="${k}"]`)
  await p.waitForSelector('text=больше не зашифрованы', { timeout: 15000 })
  await p.reload(); await p.waitForTimeout(1200)
  assert.equal(await p.locator('.lock').count(), 0)
  await p.click('.tabbar-btn:has-text("День")')
  assert.equal(await p.inputValue('.note textarea'), 'секретная заметка 2')
  const dump2 = await p.evaluate(() => Object.keys(localStorage).join(','))
  assert.ok(!dump2.includes('ottenki:data:enc'), 'зашифрованная копия удалена')
  console.log('шифрование: всё прошло', errs.length ? errs : '')
  await b.close()
})().catch(e => { console.log('ПРОВАЛ', e.message); process.exit(1) })
